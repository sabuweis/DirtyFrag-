@Composable
fun CalculatorTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) CalculatorColors.Dark else CalculatorColors.Light
    val context = LocalContext.current
    
    MaterialTheme(
        colorScheme = colorScheme.toMaterialColorScheme(),
        typography = CalculatorTypography,
        shapes = CalculatorShapes,
        content = content
    )
}

private fun CalculatorColorScheme.toMaterialColorScheme() = if (this === CalculatorColors.Dark) {
    darkColorScheme(
        primary = primary,
        onPrimary = onPrimary,
        primaryContainer = primaryContainer,
        onPrimaryContainer = onPrimaryContainer,
        secondary = secondary,
        onSecondary = onSecondary,
        secondaryContainer = surfaceContainer,
        onSecondaryContainer = onSurface,
        tertiary = surfaceContainerHigh,
        onTertiary = onSurface,
        tertiaryContainer = surface,
        onTertiaryContainer = onSurface,
        error = error,
        onError = onError,
        errorContainer = errorContainer,
        onErrorContainer = onErrorContainer,
        background = background,
        onBackground = onBackground,
        surface = surface,
        onSurface = onSurface,
        surfaceVariant = surfaceContainer,
        onSurfaceVariant = onSurfaceVariant,
        outline = outline,
        outlineVariant = outlineVariant,
        shadow = shadow,
        scrim = scrim,
        inverseSurface = inverseSurface,
        inverseOnSurface = inverseOnSurface,
        surfaceTint = surfaceTint,
    )
} else {
    lightColorScheme(
        primary = primary,
        onPrimary = onPrimary,
        primaryContainer = primaryContainer,
        onPrimaryContainer = onPrimaryContainer,
        secondary = secondary,
        onSecondary = onSecondary,
        secondaryContainer = surfaceContainer,
        onSecondaryContainer = onSurface,
        tertiary = surfaceContainerHigh,
        onTertiary = onSurface,
        tertiaryContainer = surface,
        onTertiaryContainer = onSurface,
        error = error,
        onError = onError,
        errorContainer = errorContainer,
        onErrorContainer = onErrorContainer,
        background = background,
        onBackground = onBackground,
        surface = surface,
        onSurface = onSurface,
        surfaceVariant = surfaceContainer,
        onSurfaceVariant = onSurfaceVariant,
        outline = outline,
        outlineVariant = outlineVariant,
        shadow = shadow,
        scrim = scrim,
        inverseSurface = inverseSurface,
        inverseOnSurface = inverseOnSurface,
        surfaceTint = surfaceTint,
    )
}

